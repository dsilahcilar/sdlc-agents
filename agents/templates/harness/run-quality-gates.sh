#!/usr/bin/env sh
set -eu

# FALLBACK_TEMPLATE
# Safe fallback quality gates when deterministic generation has not run yet.

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SDLC_AGENTS_ROOT="$PROJECT_ROOT/.sdlc-agents"
GENERATOR="$SDLC_AGENTS_ROOT/tools/harness/generate-harness.sh"

if [ "${SDLC_HARNESS_NO_REGEN:-0}" != "1" ] && [ -x "$GENERATOR" ]; then
  echo "[quality-gates] Attempting deterministic harness generation..."
  if "$GENERATOR" --project-root "$PROJECT_ROOT" --sdlc-agents-root "$SDLC_AGENTS_ROOT" --target-dir "$SCRIPT_DIR"; then
    if grep -q 'Generated by SDLC Harness Generator' "$SCRIPT_DIR/run-quality-gates.sh" 2>/dev/null; then
      SDLC_HARNESS_NO_REGEN=1 exec "$SCRIPT_DIR/run-quality-gates.sh" "$@"
    fi
  else
    echo "[quality-gates] ⚠ Generator failed, using fallback behavior"
  fi
fi

WARNINGS=0
FAILURES=0

run_in_project_root() {
  cmd="$1"
  (cd "$PROJECT_ROOT" && sh -c "$cmd")
}

run_soft() {
  label="$1"
  cmd="$2"
  if [ -z "$cmd" ]; then
    echo "[quality-gates] [$label] SKIP"
    return 0
  fi

  echo "[quality-gates] [$label] Running: $cmd"
  if run_in_project_root "$cmd"; then
    echo "[quality-gates] [$label] PASS"
  else
    WARNINGS=$((WARNINGS + 1))
    echo "[quality-gates] [$label] WARN"
  fi
}

echo "[quality-gates] ============================================"
echo "[quality-gates] Fallback quality gates"
echo "[quality-gates] ============================================"

if "$SCRIPT_DIR/run-feature.sh"; then
  echo "[quality-gates] [test] PASS"
else
  FAILURES=$((FAILURES + 1))
  echo "[quality-gates] [test] FAIL"
fi

if "$SCRIPT_DIR/run-arch-tests.sh"; then
  echo "[quality-gates] [arch] PASS"
else
  FAILURES=$((FAILURES + 1))
  echo "[quality-gates] [arch] FAIL"
fi

if [ -x "$SCRIPT_DIR/collect-metrics.sh" ]; then
  run_soft metrics-collect "$SCRIPT_DIR/collect-metrics.sh"
fi

if [ -x "$SCRIPT_DIR/compare-metrics.sh" ]; then
  if "$SCRIPT_DIR/compare-metrics.sh"; then
    echo "[quality-gates] [metrics-compare] PASS"
  else
    rc=$?
    if [ "$rc" -eq 1 ]; then
      WARNINGS=$((WARNINGS + 1))
      echo "[quality-gates] [metrics-compare] WARN"
    else
      FAILURES=$((FAILURES + 1))
      echo "[quality-gates] [metrics-compare] FAIL"
    fi
  fi
fi

if [ -x "$SCRIPT_DIR/archive-metrics.sh" ]; then
  run_soft metrics-archive "$SCRIPT_DIR/archive-metrics.sh"
fi

echo ""
echo "[quality-gates] ============================================"
if [ "$FAILURES" -gt 0 ]; then
  echo "[quality-gates] ✗ FAILED: $FAILURES failing phase(s), $WARNINGS warning(s)"
  exit 1
fi
if [ "$WARNINGS" -gt 0 ]; then
  echo "[quality-gates] ⚠ PASSED WITH WARNINGS: $WARNINGS warning phase(s)"
  exit 0
fi

echo "[quality-gates] ✓ PASSED"
