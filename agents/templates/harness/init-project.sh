#!/usr/bin/env sh
set -eu

# FALLBACK_TEMPLATE
# This script is safe fallback behavior for projects where deterministic
# harness generation has not run yet.

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SDLC_AGENTS_ROOT="$PROJECT_ROOT/.sdlc-agents"
GENERATOR="$SDLC_AGENTS_ROOT/tools/harness/generate-harness.sh"

if [ "${SDLC_HARNESS_NO_REGEN:-0}" != "1" ] && [ -x "$GENERATOR" ]; then
  echo "[init-project] Attempting deterministic harness generation..."
  if "$GENERATOR" --project-root "$PROJECT_ROOT" --sdlc-agents-root "$SDLC_AGENTS_ROOT" --target-dir "$SCRIPT_DIR"; then
    if grep -q 'Generated by SDLC Harness Generator' "$SCRIPT_DIR/init-project.sh" 2>/dev/null; then
      SDLC_HARNESS_NO_REGEN=1 exec "$SCRIPT_DIR/init-project.sh" "$@"
    fi
  else
    echo "[init-project] ⚠ Generator failed, using fallback behavior"
  fi
fi

detect_stack_fallback() {
  if [ -f "$SCRIPT_DIR/lib/stack-detection.sh" ]; then
    # shellcheck source=/dev/null
    . "$SCRIPT_DIR/lib/stack-detection.sh"
    detect_stack "$PROJECT_ROOT"
    return 0
  fi

  if [ -f "$PROJECT_ROOT/pom.xml" ] || [ -f "$PROJECT_ROOT/build.gradle" ] || [ -f "$PROJECT_ROOT/build.gradle.kts" ]; then
    echo "java"
  elif [ -f "$PROJECT_ROOT/package.json" ]; then
    echo "typescript"
  elif [ -f "$PROJECT_ROOT/pyproject.toml" ] || [ -f "$PROJECT_ROOT/setup.py" ] || [ -f "$PROJECT_ROOT/requirements.txt" ]; then
    echo "python"
  else
    echo "unknown"
  fi
}

STACK=$(detect_stack_fallback)
if [ "$STACK" = "javascript" ]; then
  STACK="typescript"
fi

echo "[init-project] ============================================"
echo "[init-project] Fallback initialization (stack=$STACK)"
echo "[init-project] ============================================"

case "$STACK" in
  java)
    if [ -f "$PROJECT_ROOT/pom.xml" ]; then
      sh -c 'mvn -q -DskipTests compile'
    elif [ -f "$PROJECT_ROOT/gradlew" ]; then
      sh -c './gradlew assemble --quiet'
    else
      echo "[init-project] No Java build tool wrapper detected"
    fi
    ;;
  typescript)
    if [ -f "$PROJECT_ROOT/pnpm-lock.yaml" ]; then
      sh -c 'pnpm install'
    elif [ -f "$PROJECT_ROOT/yarn.lock" ]; then
      sh -c 'yarn install'
    elif [ -f "$PROJECT_ROOT/package.json" ]; then
      sh -c 'npm install'
    else
      echo "[init-project] package.json not found"
    fi
    ;;
  python)
    if [ -f "$PROJECT_ROOT/requirements.txt" ]; then
      sh -c 'pip install -r requirements.txt'
    elif [ -f "$PROJECT_ROOT/pyproject.toml" ]; then
      sh -c 'pip install -e .'
    else
      echo "[init-project] No Python dependency manifest found"
    fi
    ;;
  *)
    echo "[init-project] No fallback init command available for stack '$STACK'"
    ;;
esac

echo "[init-project] ============================================"
echo "[init-project] Fallback initialization complete"
echo "[init-project] ============================================"
