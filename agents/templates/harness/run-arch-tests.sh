#!/usr/bin/env sh
set -eu

# FALLBACK_TEMPLATE
# Safe fallback architecture checks when deterministic generation has not run yet.

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SDLC_AGENTS_ROOT="$PROJECT_ROOT/.sdlc-agents"
GENERATOR="$SDLC_AGENTS_ROOT/tools/harness/generate-harness.sh"

if [ "${SDLC_HARNESS_NO_REGEN:-0}" != "1" ] && [ -x "$GENERATOR" ]; then
  echo "[arch-tests] Attempting deterministic harness generation..."
  if "$GENERATOR" --project-root "$PROJECT_ROOT" --sdlc-agents-root "$SDLC_AGENTS_ROOT" --target-dir "$SCRIPT_DIR"; then
    if grep -q 'Generated by SDLC Harness Generator' "$SCRIPT_DIR/run-arch-tests.sh" 2>/dev/null; then
      SDLC_HARNESS_NO_REGEN=1 exec "$SCRIPT_DIR/run-arch-tests.sh" "$@"
    fi
  else
    echo "[arch-tests] ⚠ Generator failed, using fallback behavior"
  fi
fi

detect_stack_fallback() {
  if [ -f "$SCRIPT_DIR/lib/stack-detection.sh" ]; then
    # shellcheck source=/dev/null
    . "$SCRIPT_DIR/lib/stack-detection.sh"
    detect_stack "$PROJECT_ROOT"
    return 0
  fi

  if [ -f "$PROJECT_ROOT/pom.xml" ] || [ -f "$PROJECT_ROOT/build.gradle" ] || [ -f "$PROJECT_ROOT/build.gradle.kts" ]; then
    echo "java"
  elif [ -f "$PROJECT_ROOT/package.json" ]; then
    echo "typescript"
  elif [ -f "$PROJECT_ROOT/pyproject.toml" ] || [ -f "$PROJECT_ROOT/setup.py" ] || [ -f "$PROJECT_ROOT/requirements.txt" ]; then
    echo "python"
  else
    echo "unknown"
  fi
}

STACK=$(detect_stack_fallback)
if [ "$STACK" = "javascript" ]; then
  STACK="typescript"
fi

echo "[arch-tests] ============================================"
echo "[arch-tests] Fallback architecture checks (stack=$STACK)"
echo "[arch-tests] ============================================"

case "$STACK" in
  java)
    if [ -f "$PROJECT_ROOT/pom.xml" ]; then
      sh -c 'mvn test -Dtest="*Arch*" -DfailIfNoTests=false'
    elif [ -f "$PROJECT_ROOT/gradlew" ]; then
      sh -c './gradlew test --tests "*Arch*"'
    else
      echo "[arch-tests] No Java architecture test runner detected"
    fi
    ;;
  typescript)
    if [ -f "$PROJECT_ROOT/.dependency-cruiser.js" ] || [ -f "$PROJECT_ROOT/.dependency-cruiser.cjs" ] || [ -f "$PROJECT_ROOT/.dependency-cruiser.mjs" ] || [ -f "$PROJECT_ROOT/.dependency-cruiser.json" ]; then
      CONFIG=".dependency-cruiser.js"
      if [ -f "$PROJECT_ROOT/.dependency-cruiser.cjs" ]; then CONFIG=".dependency-cruiser.cjs"; fi
      if [ -f "$PROJECT_ROOT/.dependency-cruiser.mjs" ]; then CONFIG=".dependency-cruiser.mjs"; fi
      if [ -f "$PROJECT_ROOT/.dependency-cruiser.json" ]; then CONFIG=".dependency-cruiser.json"; fi
      sh -c "npx depcruise src --config $CONFIG"
    else
      echo "[arch-tests] dependency-cruiser config not found; using madge circular check"
      sh -c 'npx madge --circular --extensions ts,tsx,js,jsx src/' || true
    fi
    ;;
  python)
    if [ -f "$PROJECT_ROOT/.importlinter" ]; then
      sh -c 'lint-imports'
    elif grep -Eq 'importlinter' "$PROJECT_ROOT/pyproject.toml" 2>/dev/null; then
      sh -c 'lint-imports'
    else
      echo "[arch-tests] import-linter not configured; skipping"
    fi
    ;;
  *)
    echo "[arch-tests] No fallback architecture checks available for stack '$STACK'"
    ;;
esac

echo "[arch-tests] ============================================"
echo "[arch-tests] Fallback architecture checks complete"
echo "[arch-tests] ============================================"
