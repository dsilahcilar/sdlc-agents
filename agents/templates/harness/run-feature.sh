#!/usr/bin/env sh
set -eu

# FALLBACK_TEMPLATE
# Safe fallback runner when deterministic generation has not run yet.

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SDLC_AGENTS_ROOT="$PROJECT_ROOT/.sdlc-agents"
GENERATOR="$SDLC_AGENTS_ROOT/tools/harness/generate-harness.sh"
FEATURE_ID="${1:-}"

if [ "${SDLC_HARNESS_NO_REGEN:-0}" != "1" ] && [ -x "$GENERATOR" ]; then
  echo "[run-feature] Attempting deterministic harness generation..."
  if "$GENERATOR" --project-root "$PROJECT_ROOT" --sdlc-agents-root "$SDLC_AGENTS_ROOT" --target-dir "$SCRIPT_DIR"; then
    if grep -q 'Generated by SDLC Harness Generator' "$SCRIPT_DIR/run-feature.sh" 2>/dev/null; then
      SDLC_HARNESS_NO_REGEN=1 exec "$SCRIPT_DIR/run-feature.sh" "$@"
    fi
  else
    echo "[run-feature] ⚠ Generator failed, using fallback behavior"
  fi
fi

detect_stack_fallback() {
  if [ -f "$SCRIPT_DIR/lib/stack-detection.sh" ]; then
    # shellcheck source=/dev/null
    . "$SCRIPT_DIR/lib/stack-detection.sh"
    detect_stack "$PROJECT_ROOT"
    return 0
  fi

  if [ -f "$PROJECT_ROOT/pom.xml" ] || [ -f "$PROJECT_ROOT/build.gradle" ] || [ -f "$PROJECT_ROOT/build.gradle.kts" ]; then
    echo "java"
  elif [ -f "$PROJECT_ROOT/package.json" ]; then
    echo "typescript"
  elif [ -f "$PROJECT_ROOT/pyproject.toml" ] || [ -f "$PROJECT_ROOT/setup.py" ] || [ -f "$PROJECT_ROOT/requirements.txt" ]; then
    echo "python"
  else
    echo "unknown"
  fi
}

STACK=$(detect_stack_fallback)
if [ "$STACK" = "javascript" ]; then
  STACK="typescript"
fi

run_in_project_root() {
  cmd="$1"
  (cd "$PROJECT_ROOT" && sh -c "$cmd")
}

echo "[run-feature] ============================================"
echo "[run-feature] Fallback feature test runner (stack=$STACK)"
echo "[run-feature] ============================================"

case "$STACK" in
  java)
    if [ -f "$PROJECT_ROOT/pom.xml" ]; then
      run_in_project_root 'mvn test'
    elif [ -f "$PROJECT_ROOT/gradlew" ]; then
      run_in_project_root './gradlew test'
    else
      echo "[run-feature] No Java test runner detected"
      exit 1
    fi
    ;;
  typescript)
    if [ -f "$PROJECT_ROOT/pnpm-lock.yaml" ]; then
      if [ -n "$FEATURE_ID" ]; then
        run_in_project_root "pnpm test -- --testPathPattern $FEATURE_ID"
      else
        run_in_project_root 'pnpm test'
      fi
    elif [ -f "$PROJECT_ROOT/yarn.lock" ]; then
      if [ -n "$FEATURE_ID" ]; then
        run_in_project_root "yarn test --testPathPattern $FEATURE_ID"
      else
        run_in_project_root 'yarn test'
      fi
    elif [ -f "$PROJECT_ROOT/package.json" ]; then
      if [ -n "$FEATURE_ID" ]; then
        run_in_project_root "npm test -- --testPathPattern $FEATURE_ID"
      else
        run_in_project_root 'npm test'
      fi
    else
      echo "[run-feature] package.json not found"
      exit 1
    fi
    ;;
  python)
    if command -v pytest >/dev/null 2>&1; then
      if [ -n "$FEATURE_ID" ]; then
        run_in_project_root "pytest -k $FEATURE_ID"
      else
        run_in_project_root 'pytest'
      fi
    else
      run_in_project_root 'python -m unittest discover'
    fi
    ;;
  *)
    echo "[run-feature] No fallback test command available for stack '$STACK'"
    exit 1
    ;;
esac

echo "[run-feature] ============================================"
echo "[run-feature] Fallback feature tests complete"
echo "[run-feature] ============================================"
