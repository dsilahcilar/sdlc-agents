#!/usr/bin/env sh
set -eu

usage() {
  cat <<'USAGE'
Usage: validate-generated-harness.sh [options]

Validate generated harness scripts.

Options:
  --project-root <path>  Project root (default: current directory)
  --target-dir <path>    Harness directory (default: <project-root>/agent-context/harness)
  -h, --help             Show this help message
USAGE
}

PROJECT_ROOT=""
TARGET_DIR=""

while [ $# -gt 0 ]; do
  case "$1" in
    --project-root)
      PROJECT_ROOT="${2:-}"
      shift 2
      ;;
    --target-dir)
      TARGET_DIR="${2:-}"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "[harness-validate] ERROR: Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

if [ -z "$PROJECT_ROOT" ]; then
  PROJECT_ROOT=$(pwd)
fi
PROJECT_ROOT=$(cd "$PROJECT_ROOT" && pwd)

if [ -z "$TARGET_DIR" ]; then
  TARGET_DIR="$PROJECT_ROOT/agent-context/harness"
fi

if [ ! -d "$TARGET_DIR" ]; then
  echo "[harness-validate] ERROR: Harness directory not found: $TARGET_DIR" >&2
  exit 1
fi

required_scripts="init-project.sh run-feature.sh run-arch-tests.sh run-quality-gates.sh"
errors=0

check_script() {
  path="$1"

  if [ ! -f "$path" ]; then
    echo "[harness-validate] ✗ Missing file: $path"
    errors=$((errors + 1))
    return
  fi

  if [ ! -x "$path" ]; then
    echo "[harness-validate] ✗ Not executable: $path"
    errors=$((errors + 1))
  fi

  if ! sh -n "$path" >/dev/null 2>&1; then
    echo "[harness-validate] ✗ Syntax error: $path"
    errors=$((errors + 1))
  fi

  if ! grep -q 'Generated by SDLC Harness Generator' "$path"; then
    echo "[harness-validate] ✗ Missing generator marker: $path"
    errors=$((errors + 1))
  fi

  if grep -q 'FALLBACK_TEMPLATE' "$path"; then
    echo "[harness-validate] ✗ Script is still fallback template: $path"
    errors=$((errors + 1))
  fi
}

for script in $required_scripts; do
  check_script "$TARGET_DIR/$script"
done

QUALITY_PATH="$TARGET_DIR/run-quality-gates.sh"
if [ -f "$QUALITY_PATH" ]; then
  if ! grep -q 'run_phase test' "$QUALITY_PATH"; then
    echo "[harness-validate] ✗ Missing test phase in run-quality-gates.sh"
    errors=$((errors + 1))
  fi
  if ! grep -q 'run-arch-tests.sh' "$QUALITY_PATH"; then
    echo "[harness-validate] ✗ Missing architecture phase wiring in run-quality-gates.sh"
    errors=$((errors + 1))
  fi
fi

if [ "$errors" -gt 0 ]; then
  echo "[harness-validate] ✗ Validation failed with $errors error(s)"
  exit 1
fi

echo "[harness-validate] ✓ Generated harness validation passed"
